export function comparisonNameEs(compareItem: string | null | undefined): string {
  const original=compareItem?.trim()||'';
  return COMPARISON_LABEL_ES[original]||original;
}
export function productNameEs(product: {item_en:string;item_es:string|null|undefined}): string {
  return product.item_es?.trim() || MISSING_PRODUCT_LABEL_ES[product.item_en?.trim()] || product.item_en;
}
export function foldSpanish(value: string): string {
  return value.normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLocaleLowerCase('es');
}
export function matchesGroceryQuery(
  product:{
    item_en:string;item_es:string|null|undefined;
    compare_item:string|null|undefined;chain:string;department:string;brand:string|null|undefined
  },
  query:string
):boolean {
  const needle=foldSpanish(query.trim());
  if(!needle)return true;
  return foldSpanish([
    productNameEs(product),product.item_en,product.compare_item,
    comparisonNameEs(product.compare_item),product.chain,product.department,product.brand
  ].filter(Boolean).join(' ')).includes(needle);
}

